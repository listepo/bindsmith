/// `bindsmith.lock` (plan P3-3).
///
/// The lock is read far more often than it is written — every `--offline`
/// build and every CI check reads one — so the parser's job is to refuse a
/// file it does not understand with a line and a column, exactly as the
/// configuration loader does, rather than to resolve half of it.
library;

import 'dart:convert';

import 'package:bindsmith/bindsmith.dart';
import 'package:crypto/crypto.dart' as crypto;
import 'package:test/test.dart';

/// A digest of the shape the parser insists on, derived from the coordinate so
/// that an expectation can name one without copying 64 characters around.
String _digest(String coordinate) =>
    crypto.sha256.convert(utf8.encode(coordinate)).toString();

LockedArtifact _artifact(String coordinate, {String extension = 'jar'}) =>
    (coordinate: coordinate, extension: extension, sha256: _digest(coordinate));

List<String> _problems(String source) {
  try {
    parseLockfile(source);
    fail('expected the lock to be refused');
  } on LockException catch (e) {
    return e.problems;
  }
}

void main() {
  group('writing', () {
    test('sorts by coordinate, so reordering the config changes nothing', () {
      final forwards = writeLockfile(
        Lockfile({
          'maven': [
            _artifact('com.example:zebra:1.0'),
            _artifact('androidx.core:core:1.13.1', extension: 'aar'),
          ],
        }),
      );
      final backwards = writeLockfile(
        Lockfile({
          'maven': [
            _artifact('androidx.core:core:1.13.1', extension: 'aar'),
            _artifact('com.example:zebra:1.0'),
          ],
        }),
      );
      expect(forwards, backwards);
      expect(
        forwards.indexOf('androidx.core'),
        lessThan(forwards.indexOf('com.example')),
      );
    });

    test('says it is generated and how to regenerate it', () {
      final text = writeLockfile(
        Lockfile({
          'maven': [_artifact('a:b:1')],
        }),
      );
      expect(text, startsWith('# GENERATED BY bindsmith'));
      expect(text, contains('bindsmith resolve'));
      expect(text, contains('version: ${Lockfile.formatVersion}'));
    });

    test('leaves out a kind that resolved to nothing', () {
      expect(writeLockfile(Lockfile({'maven': []})), isNot(contains('maven')));
    });
  });

  group('reading', () {
    test('round-trips what was written', () {
      final lock = Lockfile({
        'maven': [
          _artifact('com.example:demo:1.0'),
          _artifact('androidx.core:core:1.13.1', extension: 'aar'),
        ],
      });
      final read = parseLockfile(writeLockfile(lock));
      expect(read.digests, lock.digests);
      expect(read.artifacts['maven']!.first.extension, 'aar');
    });

    test('keys the digests by kind and coordinate', () {
      final lock = Lockfile({
        'maven': [_artifact('com.example:demo:1.0')],
      });
      expect(lock.digests, {
        'maven com.example:demo:1.0': _digest('com.example:demo:1.0'),
      });
    });

    // A digest of nothing but decimal digits is a YAML number, and one long
    // enough to outgrow an integer becomes a float — so the value the parser
    // is handed is not a string, through no fault of whoever wrote the file.
    // A lock written before bindsmith quoted the digest has the same shape.
    for (final digit in ['0', '1']) {
      test('reads a digest of nothing but $digit, unquoted', () {
        final digest = digit * 64;
        final lock = parseLockfile(
          'version: 1\n'
          'maven:\n'
          '  - coordinate: com.example:demo:1.0\n'
          '    extension: jar\n'
          '    sha256: $digest\n',
        );
        expect(lock.artifacts['maven']!.single.sha256, digest);
      });
    }

    test('refuses a sha256 that is not a digest at all', () {
      // Uppercase included: it would never equal a freshly computed digest,
      // so accepting it would report changed bytes on every run instead.
      for (final written in ['nope', 'true', 'a' * 63, 'A' * 64]) {
        expect(
          _problems(
            'version: 1\n'
            'maven:\n'
            '  - coordinate: com.example:demo:1.0\n'
            '    extension: jar\n'
            '    sha256: $written\n',
          ).single,
          contains('64 lowercase hex characters'),
          reason: '"$written" is not a digest',
        );
      }
    });

    test('refuses a lock written by a version that is not this one', () {
      expect(_problems('version: 99\n'), [
        contains('lockfile format 99 is not 1'),
      ]);
    });

    test('refuses a file that is not a lock at all', () {
      expect(_problems('name: demo\n').first, contains('no "version"'));
      expect(_problems('- one\n- two\n'), [contains('expected "version:"')]);
    });

    test('refuses a kind nothing resolves, rather than dropping it', () {
      expect(
        _problems('version: 1\ncargo:\n  - coordinate: serde\n').single,
        allOf(
          contains('"cargo" is not a kind of dependency'),
          contains('maven, npm, nuget'),
        ),
      );
    });

    test('round-trips npm and nuget sections', () {
      final lock = Lockfile({
        'npm': [_artifact('chart.js@4.4.7', extension: 'tgz')],
        'nuget': [
          _artifact(
            'Microsoft.Windows.SDK.Win32Metadata@60.0.34-preview',
            extension: 'nupkg',
          ),
        ],
      });
      final read = parseLockfile(writeLockfile(lock));
      expect(read.artifacts['npm']!.single.extension, 'tgz');
      expect(read.artifacts['nuget']!.single.extension, 'nupkg');
      expect(read.digests, lock.digests);
    });

    test('refuses an entry that is missing a field', () {
      expect(_problems('version: 1\nmaven:\n  - coordinate: a:b:1\n'), [
        contains('no "extension"'),
        contains('no "sha256"'),
      ]);
    });

    test('refuses a field that is not part of a locked file', () {
      expect(
        _problems(
          'version: 1\n'
          'maven:\n'
          '  - coordinate: a:b:1\n'
          '    extension: jar\n'
          "    sha256: '${_digest('a:b:1')}'\n"
          '    repository: https://example.invalid/\n',
        ),
        [contains('"repository" is not part of a locked file')],
      );
    });

    test('refuses a sha256 that is not a scalar', () {
      expect(
        _problems(
          'version: 1\n'
          'maven:\n'
          '  - coordinate: a:b:1\n'
          '    extension: jar\n'
          '    sha256: [1, 2]\n',
        ).single,
        contains('"sha256" takes a string'),
      );
    });

    test('refuses a section that is not a list', () {
      expect(_problems('version: 1\nmaven: everything\n'), [
        contains('"maven" takes a list'),
      ]);
    });

    test('reports every problem, not the first', () {
      expect(
        _problems(
          'maven:\n'
          '  - coordinate: a:b:1\n'
          '  - just a string\n',
        ),
        hasLength(4), // no version, no extension, no sha256, not a mapping
      );
    });

    test('reports a problem with the line it is on', () {
      expect(_problems('version: 1\nmaven: nope\n').single, contains('line 2'));
    });

    test('refuses YAML it cannot even parse', () {
      expect(_problems('version: [1\n'), isNotEmpty);
    });
  });
}
