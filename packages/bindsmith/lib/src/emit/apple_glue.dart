/// The Apple side of an Objective-C or Swift binding (plan P2-3): what a
/// CocoaPods podspec and a SwiftPM target need so the generated `.m` glue is
/// compiled and linked.
///
/// Neither snippet is the author's podspec or `Package.swift` itself — those
/// files belong to the package author. Each emitted file says what to add
/// (`s.source_files`, `s.frameworks`, `ffiPlugin`, target `sources`,
/// `linkerSettings`) and carries the lines to merge.
///
/// [Layout.glue] is the only source for where the `.m` lives; nothing here
/// joins paths to the binding or the glue on its own.
library;

import '../ir/ir.dart';
import 'layout.dart';

/// Beside-package path for the CocoaPods snippet, relative to `bindsmith.yaml`.
String applePodspecPath(Platform platform) =>
    '${platform.name}/bindsmith.podspec.snippet';

/// Beside-package path for the SwiftPM snippet, relative to `bindsmith.yaml`.
String applePackageSwiftPath(Platform platform) =>
    '${platform.name}/bindsmith.Package.swift.snippet';

/// Extra Apple tooling [doctor] should report once P3-6 extends it (plan
/// P2-3): Xcode and swiftc are already checked; the iOS Simulator SDK path
