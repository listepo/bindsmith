/// `bindsmith.lock` (plan P3-3): exactly which bytes a resolution produced.
///
/// A configuration says `androidx.biometric:biometric:1.2.0-alpha05`; the lock
/// says which file that turned out to be and what its digest was. Everything
/// that makes one coordinate mean different bytes on a different day — version
/// ranges, `LATEST`, `-SNAPSHOT` — is refused at resolution rather than
/// written down here, so a lock entry is a fact and not a guess.
///
/// Which repository served the bytes is deliberately not recorded. Once the
/// digest matches, where it came from does not change what you compiled
/// against, and recording it would make a lock churn every time a mirror is
/// added.
library;

import 'package:yaml/yaml.dart';

/// Thrown when `bindsmith.lock` cannot be used, carrying every problem found.
final class LockException implements Exception {
  const LockException(this.problems);

  /// One entry per problem, each already formatted with its line and column.
  final List<String> problems;

  @override
  String toString() =>
      'bindsmith.lock is not usable:\n\n${problems.join('\n\n')}';
}

/// One resolved file: what was asked for, and what arrived.
typedef LockedArtifact = ({String coordinate, String extension, String sha256});

/// The kinds of dependency a lock can hold. A kind is added here when its
/// resolver lands; until then an entry under that name is refused rather than
/// ignored, so a typo cannot look like a working lock.
const lockKinds = {'maven', 'npm', 'nuget'};

final class Lockfile {
  Lockfile(Map<String, List<LockedArtifact>> artifacts)
    : artifacts = {
        for (final kind in lockKinds)
          if (artifacts[kind] case final locked? when locked.isNotEmpty)
            kind: _sorted(locked),
      };

  /// Bumped when the format changes so that an older bindsmith would read it
  /// wrongly. Reading a version it does not know is an error, never a guess.
  static const formatVersion = 1;

  /// The file name, beside `bindsmith.yaml`.
  static const fileName = 'bindsmith.lock';

  /// Kind → what it resolved to, sorted by coordinate so that reordering the
  /// configuration cannot rewrite the lock (rule 6).
  final Map<String, List<LockedArtifact>> artifacts;

  /// Every entry as `kind coordinate` → digest, which is what a comparison
  /// works on.
  Map<String, String> get digests => {
    for (final MapEntry(key: kind, value: locked) in artifacts.entries)
      for (final artifact in locked)
        '$kind ${artifact.coordinate}': artifact.sha256,
  };

  static List<LockedArtifact> _sorted(List<LockedArtifact> artifacts) =>
      [...artifacts]..sort((a, b) => a.coordinate.compareTo(b.coordinate));
}

/// The lockfile as text, newline included.
String writeLockfile(Lockfile lock) {
  final out = StringBuffer()
    ..writeln('# GENERATED BY bindsmith — do not edit.')
    ..writeln('# Run "bindsmith resolve" to update it, and commit the result.')
    ..writeln('version: ${Lockfile.formatVersion}');
  for (final MapEntry(key: kind, value: locked) in lock.artifacts.entries) {
    out.writeln('$kind:');
    for (final artifact in locked) {
      out
        ..writeln('  - coordinate: ${artifact.coordinate}')
        ..writeln('    extension: ${artifact.extension}')
        // Quoted, because a hex digest that happened to be all decimal digits
        // is a number to YAML. [parseLockfile] reads one either way, but this
        // file is also read by whatever a build script uses, and those hit the
        // same trap with no such fallback.
        ..writeln("    sha256: '${artifact.sha256}'");
    }
  }
  return out.toString();
}

/// Reads a lockfile, reporting *every* problem with its line and column.
Lockfile parseLockfile(String source, {Uri? sourceUrl}) {
  final YamlNode root;
  try {
    root = loadYamlNode(source, sourceUrl: sourceUrl);
  } on YamlException catch (e) {
    throw LockException([e.span?.message(e.message) ?? e.message]);
  }
  if (root is! YamlMap) {
    throw LockException([
      root.span.message(
        'expected "version:" and a section per dependency kind',
      ),
    ]);
  }

  final problems = <String>[];
  switch (root.nodes['version']) {
    case null:
      problems.add(
        root.span.message('no "version": this is not a bindsmith.lock'),
      );
    case final YamlNode node when node.value != Lockfile.formatVersion:
      problems.add(
        node.span.message(
          'lockfile format ${node.value} is not ${Lockfile.formatVersion}; '
          'delete bindsmith.lock and run "bindsmith resolve"',
        ),
      );
    default:
  }

  final artifacts = <String, List<LockedArtifact>>{};
  for (final MapEntry(key: key, value: value) in root.nodes.entries) {
    final name = (key as YamlNode).value;
    if (name == 'version') continue;
    if (name is! String || !lockKinds.contains(name)) {
      problems.add(
        key.span.message(
          '"$name" is not a kind of dependency bindsmith resolves; '
          'it locks ${lockKinds.join(', ')}',
        ),
      );
      continue;
    }
    artifacts[name] = _artifacts(name, value, problems);
  }

  if (problems.isNotEmpty) throw LockException(problems);
  return Lockfile(artifacts);
}

/// What `crypto` prints for a sha256, and the only thing a lock may pin with:
/// lowercase, because an uppercase copy would never equal a freshly computed
/// digest and would be reported as changed bytes on every run.
final _digest = RegExp(r'^[0-9a-f]{64}$');

List<LockedArtifact> _artifacts(
  String kind,
  YamlNode node,
  List<String> problems,
) {
  if (node is! YamlList) {
    problems.add(node.span.message('"$kind" takes a list of locked files'));
    return const [];
  }
  final artifacts = <LockedArtifact>[];
  for (final entry in node.nodes) {
    if (entry is! YamlMap) {
      problems.add(
        entry.span.message('expected coordinate, extension and sha256'),
      );
      continue;
    }
    for (final key in entry.nodes.keys) {
      final name = (key as YamlNode).value;
      if (name case 'coordinate' || 'extension' || 'sha256') continue;
      problems.add(key.span.message('"$name" is not part of a locked file'));
    }
    final fields = <String, String>{};
    for (final field in ['coordinate', 'extension', 'sha256']) {
      final value = entry.nodes[field];
      switch (value) {
        case null:
          problems.add(entry.span.message('no "$field"'));
        case YamlNode(value: final String text):
          fields[field] = text;
        // A digest of nothing but decimal digits is a number to YAML — an
        // integer, or a float once it outgrows one — and so is a digest in a
        // lock written before bindsmith quoted it. Neither is a mistake by
        // whoever wrote the file, so read what the file says rather than what
        // YAML made of it, and let [_digest] decide whether it is one.
        case YamlScalar() when field == 'sha256':
          fields[field] = value.span.text;
        case _:
          problems.add(value.span.message('"$field" takes a string'));
      }
    }
    if (fields.length != 3) continue;
    // Checked rather than trusted, because the fallback above hands back
    // whatever the file said. A digest that is not one would otherwise be
    // compared against a real one and reported as bytes that changed, which
    // sends the reader looking for a compromised mirror.
    if (!_digest.hasMatch(fields['sha256']!)) {
      problems.add(
        entry.nodes['sha256']!.span.message(
          'expected a sha256 digest: 64 lowercase hex characters',
        ),
      );
      continue;
    }
    artifacts.add((
      coordinate: fields['coordinate']!,
      extension: fields['extension']!,
      sha256: fields['sha256']!,
    ));
  }
  return artifacts;
}
