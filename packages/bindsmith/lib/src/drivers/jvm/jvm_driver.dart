/// JVM driver: runs jnigen 1.0 through its library API and lifts the result
/// into the IR.
///
/// Like ffigen, jnigen's public AST (`ClassDecl`, `Method`, `Field`, `Param`)
/// carries names and inclusion but no types, and its visitors run *before*
/// renaming, so the Dart names are not known there. The generated Dart is the
/// source of truth instead: jnigen writes the Java binary name and the full
/// signature into a `/// from:` doc line on every declaration, which
/// [jvmToIr] reads back with `package:analyzer` (syntax only). For a member
/// with Kotlin metadata that line is the Kotlin signature
/// (`public suspend fun greetSlowly(name: kotlin.String): kotlin.String`), and
/// it is where the IR takes Kotlin's parameter names from: the Dart ones are
/// the bytecode's (`string`, `i`).
///
/// Mapping (Java / Kotlin → generated Dart → IR):
///
/// | Java / Kotlin           | IR                                               |
/// |-------------------------|--------------------------------------------------|
/// | class                   | `TypeDecl(klass)`, `id` = binary name            |
/// | interface               | `TypeDecl(interface)` + implementable marker     |
/// | enum                    | `TypeDecl(enumeration)`, constants as properties |
/// | nested class `A.B`      | one decl named `A$B` (jnigen's Dart name)        |
/// | constructor             | `Member('', constructor)`, `binding` = `new$1` … |
/// | method / static method  | `Member(method, isStatic:)`                      |
/// | field                   | `property` (+ `setter` when writable)            |
/// | unincluded dependency   | `TypeDecl` with a dropped marker (jnigen stub)   |
/// | `suspend fun f(): T`    | method, `returns` = `T`, `async: future`         |
/// | returns `Flow<T>`       | method + verify marker (`emitKotlinBridge`)      |
/// | default argument        | dropped `f$default`, read from the class file    |
/// | synthetic member        | member + dropped marker                          |
///
/// Types keep their `package:jni` spelling (`JString`, `JList<JString?>`);
/// `TypeRef.native` holds the Java or Kotlin type. The facade marshals
/// `JString` ↔ `String`.
///
/// @docImport '../../emit/kotlin_bridge.dart';
